// Is the fixed-point criterion's INPUT right at X_0^6(379)*?  Three independent checks on the
// elliptic-point data, none of which reuses the routine that produced it.
//
//  (1) the orbifold genus.  With the arithmetic volume (Eichler mass formula) the elliptic data
//      determines the genus, and the answer has to be the integer 3; wrong counts almost never
//      give an integer.
//  (2) class numbers.  A CM point of discriminant d on the star curve is defined over a subfield
//      of the ring class field of the order of discriminant d, so its degree must DIVIDE h(d),
//      with quotient the order of the subgroup of the class group generated by the primes above
//      the divisors of D*N -- a group of order dividing 2^omega(D*N) = 8 here.  So h(d)/degree
//      must be an integer dividing 8.
//  (3) a second code path for the counts: NumFixedPointsByCMOrder is the repository's Ogg
//      formula and is independent of NumberOfEllipticPointsByCMOrder.
AttachSpec("/Users/assaferan/Documents/GitHub/ShimuraCurveALQuotients/worktrees/campaign/ShimuraQuotients.spec");
SetColumns(0);
D := 6; N := 379; DN := D*N;
full := { Integers() | d : d in Divisors(DN) | GCD(d, DN div d) eq 1 };
X := CreateShimuraQuot(D, N, full);
X`g := GenusShimuraCurveQuotient(D, N, full);
printf "X_0^%o(%o)*  W = %o  genus %o\n", D, N, Sort(SetToSequence(full)), X`g;

V := ArithmeticVolume(FuchsianGroup(MaximalOrder(QuaternionAlgebra(D))));
printf "arithmetic volume of X_0^%o(1): %o\n", D, V;

ell := NumberOfEllipticPointsByCMOrder(X);
printf "\n(1) elliptic points of X* by stabiliser order and discriminant:\n";
tot := 0; byq := AssociativeArray();
for q in Sort(SetToSequence(Keys(ell))) do
    s := 0;
    for d in Sort(SetToSequence(Keys(ell[q]))) do
        n := ell[q][d];
        if n eq 0 then continue; end if;
        printf "   order %o, discriminant %-7o : %o points\n", q, d, n;
        s +:= n; tot +:= n;
    end for;
    byq[q] := s;
end for;
printf "   total elliptic points: %o\n", tot;

// orbifold genus from the volume and the elliptic data
psi := N; for pr in PrimeDivisors(N) do psi := psi*(pr+1) div pr; end for;
vq := V*psi/#full;
rhs := vq;
for q in Keys(byq) do rhs -:= byq[q]*(1 - 1/q); end for;
rhs := rhs/2;
printf "\n   arithmetic volume of X* = %o\n", vq;
printf "   genus from 1 + vol/2 - sum e_q (1 - 1/q)/2 ... computed g = %o, formula g = %o\n",
       X`g, 1 + rhs;
printf "   CONSISTENT: %o\n", (1 + rhs) eq X`g;

printf "\n(2) class numbers against the field degrees reported by the criterion:\n";
for d in [-3, -379, -4548, -9096] do
    h := ClassNumber(QuadraticForms(d));
    ok := true; deg := 0;
    try deg := Degree(AbsoluteField(FieldOfDefinitionOfCMPoint(X, d))); catch e ok := false; end try;
    npts := 0;
    for q in Keys(ell) do if d in Keys(ell[q]) then npts +:= ell[q][d]; end if; end for;
    printf "   d = %-7o fundamental %-5o h(d) = %-4o field degree %-4o points %-4o h/deg = %o\n",
       d, IsFundamentalDiscriminant(d), h, ok select deg else -1, npts,
       (ok and deg gt 0) select (IsIntegral(h/deg) select Sprintf("%o%o", h div deg,
           (h mod deg eq 0 and 8 mod (h div deg) eq 0) select " (divides 8, OK)"
           else " <== DOES NOT DIVIDE 8") else "NOT AN INTEGER <== PROBLEM")
       else "n/a";
end for;

printf "\n(3) fixed points of each Atkin-Lehner involution on X_0^%o(%o), second code path:\n", D, N;
for m in Sort(SetToSequence(full)) do
    if m eq 1 then continue; end if;
    fp := NumFixedPointsByCMOrder(D, N, m);
    s := 0; det := [];
    for d in Sort(SetToSequence(Keys(fp))) do
        if fp[d] eq 0 then continue; end if;
        s +:= fp[d]; Append(~det, <d, fp[d]>);
    end for;
    printf "   w_%-6o total %-4o by discriminant %o\n", m, s, det;
end for;
printf "CHK379 DONE\n";
quit;
