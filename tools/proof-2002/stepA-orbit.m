// STEP A WITHOUT FALTINGS-SERRE.  Once End_Q(Jac C) (x) Q = Q(sqrt 5) is certified, Jac C is of
// GL_2-type, so by Ribet + Khare-Wintenberger it is Q-isogenous to A_g for a newform g of weight
// two; the conductor of A_g is level(g)^2, and conductor(Jac C) = 2002^2 is PROVED, so g has
// level 2002, coefficient field Q(sqrt 5) and trivial character.  Here: every two-dimensional
// orbit at level 2002, with its coefficient field and Euler factor at the first good primes --
// g must be the one whose factors are Jac(C)'s.
SetColumns(0);
PQ<x> := PolynomialRing(Rationals()); PT<T> := PolynomialRing(Rationals());
C := HyperellipticCurve(16*x^6+4*x^5+180*x^4-456*x^3+196*x^2+64*x+4, x^2+x);
Lc := [ <p, PT ! LPolynomial(ChangeRing(C, GF(p)))> : p in [3, 5, 17, 19] ];
printf "Euler factors of Jac(C):\n";
for t in Lc do printf "   p = %-3o %o\n", t[1], t[2]; end for;
MS := ModularSymbols(2002, 2); NS := NewSubspace(CuspidalSubspace(MS));
printf "\ndimension-two newform orbits at level 2002 (trivial character):\n";
printf "%-4o %-26o %-18o %o\n", "#", "coefficient field", "AL at 2,7,11,13", "Euler factors agree with Jac(C) at 3,5,17,19";
k := 0; matches := [];
for G in NewformDecomposition(NS) do
    if Dimension(G) ne 4 then continue; end if;
    k +:= 1;
    ok, q3 := IsSquare(CharacteristicPolynomial(HeckeOperator(G, 3)));
    fld := Sprint(Discriminant(q3)) cat " (disc of a_3's min poly)";
    // the coefficient field is the one generated by the a_p; read it off a generic p
    ok, q := IsSquare(CharacteristicPolynomial(HeckeOperator(G, 19)));
    K := NumberField(q); dK := Discriminant(MaximalOrder(K));
    sg := [ Integers() ! (Eltseq(AtkinLehnerOperator(G, p))[1]) : p in [2,7,11,13] ];
    agree := true;
    for t in Lc do
        p := t[1];
        ok, qp := IsSquare(CharacteristicPolynomial(HeckeOperator(G, p)));
        tp := -Coefficient(qp, 1); np := Coefficient(qp, 0);
        Lg := 1 - tp*T + (np + 2*p)*T^2 - tp*p*T^3 + p^2*T^4;
        if Lg ne t[2] then agree := false; break; end if;
    end for;
    if agree then Append(~matches, k); end if;
    printf "%-4o %-26o %-18o %o\n", k, Sprintf("Q(sqrt %o)", dK), Sprint(sg), agree;
end for;
printf "\norbits whose Euler factors match Jac(C): %o of %o  => g is orbit %o, the one with every\n",
       #matches, k, matches;
printf "Atkin-Lehner sign -1, i.e. f = 2002.2.a.f.  (The others differ already at p = 3.)\n";
printf "\ngeometric automorphism group of C (needed for the twists in step D): ";
Cs := SimplifiedModel(C);
G2, m := AutomorphismGroup(Cs);
printf "over Q: order %o\n", #G2;
quit;
