// CM-value (Borcherds/Schofer) special-fiber non-hyperellipticity test for genus-0 Shimura
// curves X_0(D,1) whose star quotient is NOT an arithmetic triangle group -- so there is no
// closed-form hypergeometric supersingular polynomial as in the D=6 case (special_fiber_modular.m).
//
// This is the GENERAL method (complementing the D=6 hypergeometric one and the Heun/ODE method):
// it works for any discriminant for which the repo's Borcherds/Schofer pipeline produces the star
// Hauptmodul and the cover equations -- important for larger D that admit no simple ODE description.
//
// Method (instantiated below for D=10, whose star is the (2,2,2,3) quadrilateral orbifold).
//   1. The supersingular points of X_0(D,1) mod p are the left-ideal classes of the definite
//      quaternion algebra of discriminant D*p; their count, Frobenius (= w_p) and Atkin-Lehner
//      action are given by SupersingularALData (special_fiber_modular.m, the Brandt layer).
//   2. Star coordinates.  The GENERIC supersingular points (away from the four elliptic cone
//      points s = 0, 1, 2/27, oo) are the roots of the (2,2,2,3) Heun Picard-Fuchs polynomial --
//      the closed-form analog of the D=6 hypergeometric d6_hypg (see d10cm_heun_generic below).
//      This gives full coverage at every prime.  The CM-value data (a finite disc->s table from
//      the Borcherds/Schofer pipeline) is retained only to pin the Heun accessory eigenvalue via
//      a single known generic root, and to interpolate the intermediate cover equations f_q.
//      (The original purely-CM coordinate reduction is exact too, but bounded in prime range and
//      blocked by tooling limits on quadratic discriminants; the Heun route removes both limits.)
//   3. The genus-0 intermediate quotient X_0(D,1)/<w_q> is a conic y^2 = f_q(s) over the star;
//      lifting each star coordinate s_i through it yields the intermediate supersingular points
//      (s_i, +-sqrt(f_q(s_i))) -- and a non-square f_q(s_i) produces a non-F_p-rational
//      (constrained) point, which is what gives the Mobius test (has_compat) its leverage.
//   4. has_compat then tests for a compatible (Frobenius-on-ss, F_p-rational) Mobius involution
//      exactly as in the D=6 case; its absence proves NOT (geometrically) hyperelliptic.
//
// The D=10 data below was generated by, and is cross-checked against, the live pipeline:
//   Xstar := the D=10,N=1 star;  ValuesAtCMPoints(Xstar, curves)  gives the disc->s table
//   (key -1) and the intermediate cover y^2 values (the cover-label keys), from which f_q is
//   interpolated.  Validated (tests/SpecialFiberD10.m): the Heun supersingular set matches the
//   star count (genus formula) on every call and the CM-value supersingular set exactly where both are
//   available; 0 contradictions against the known-hyperelliptic D=10 curves; proves 69 of the
//   reached intermediate-quotient curves non-hyperelliptic, including X_0(10,71)/<w_10,w_71>
//   (g=3), previously undetermined -- the first new D=10 determination from this test.

// ---------------------------------------------------------------------------
// D = 10 precomputed CM-value data (rational CM discriminants, class number <= 4).
// disc d  ->  star Hauptmodul value s(P_d).  Pole (s = oo) at the order-3 point (d = -3).
d10cm_discs := [Integers()|
  -3, -8, -20, -40, -35, -43, -52, -67, -88, -115, -120, -148, -163, -232, -235, -280, -340, -520, -760];
