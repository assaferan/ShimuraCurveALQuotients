// ---- P^1 helpers + has_compat (same logic as special_fiber_modular.m) ----
function cm_aut01oo(t)
  p0:=t[1]; p1:=t[2]; poo:=t[3];
  c0:=p1[1]*p0[2]-p0[1]*p1[2]; d0:=poo[1]*p1[2]-p1[1]*poo[2];
  return Matrix([[c0*poo[1], p0[1]*d0],[c0*poo[2], d0*p0[2]]]);
end function;
function cm_mobm(o,d) return cm_aut01oo(d)*cm_aut01oo(o)^(-1); end function;
cm_app := func<g,pt | [g[1,1]*pt[1]+g[1,2]*pt[2], g[2,1]*pt[1]+g[2,2]*pt[2]]>;
cm_eqP := func<a,b | a[1]*b[2]-a[2]*b[1] eq 0>;
function cm_has_compat(qss, p, F, case2)
  frob := func<pt | [Frobenius(pt[1]),Frobenius(pt[2])]>;
  pts := case2 select [Q : Q in qss | not cm_eqP(frob(Q),Q)] else qss;   // case 2: non-F_p ss only
  if #pts lt 3 then return "underdet"; end if;
  g := cm_mobm([pts[1],pts[2],pts[3]], [frob(pts[1]),frob(pts[2]),frob(pts[3])]);
  if not &and[cm_eqP(cm_app(g,Q),frob(Q)) : Q in pts] then return "no"; end if;
  if g[1,2] eq 0 and g[2,1] eq 0 and g[1,1] eq g[2,2] then return "underdet"; end if;
  s := exists(c){x : x in [g[1,1],g[1,2],g[2,1],g[2,2]] | x ne 0} select c else F!1;
  if not &and[x in GF(p) : x in [g[1,1]/s,g[1,2]/s,g[2,1]/s,g[2,2]/s]] then return "no"; end if;
  return "yes";
end function;

// reduce a rational (or Infinity) Hauptmodul value to P^1(F_p): <coord, isInfinity>.
function d10cm_redP1(v, p)
  if Type(v) eq Infty then return <GF(p)!0, true>; end if;
  if Denominator(v) mod p eq 0 then return <GF(p)!0, true>; end if;
  return <GF(p)!v, false>;
end function;

// generic star supersingular coordinates KNOWN from the rational CM disc->s table (in F_p),
// excluding the cone points s = 0, 1, 2/27; used to pin the Heun accessory eigenvalue below.
function d10cm_known_generic(p)
  F := GF(p); cone := {F!0, F!1, F!(2/27)};
  cs := {};
  for i in [1..#d10cm_discs] do
    if KroneckerSymbol(d10cm_discs[i], p) ne 1 then
      r := d10cm_redP1(d10cm_s[i], p);
      if (not r[2]) and (r[1] notin cone) then Include(~cs, r[1]); end if;
    end if;
  end for;
  return cs;
end function;

// ---- (2,2,2,3) Heun supersingular polynomial (closed form, full coverage) ----
// The generic supersingular points of X_0(10,1) -- those away from the elliptic cone points
// s = 0, 1, 2/27, oo (CM discs -8, -20, -40, -3) -- are the roots of the polynomial solution of
//     s(s-1)(s-2/27) y'' + [g(s-1)(s-2/27)+d s(s-2/27)+e s(s-1)] y' + (ab*s - q) y = 0,
// the (2,2,2,3) Picard-Fuchs / Heun equation of the QM family (the analog of the (2,4,6)
// hypergeometric d6_hypg for D=6).  Derived facts: the exponent at each order-2 cone point is
// 1/2 if the point is ordinary and 3/2 if supersingular; the infinity-product ab is fixed by the
// polynomial degree N via the Fuchs relation; and the accessory parameter q is an eigenvalue of
// the Heun operator (squared away the leading term), selected by requiring a known generic root.
// Validated: recovers the full CM-value supersingular set exactly on all available primes, and
// extends to every prime with no coverage ceiling (unlike the rational-CM-disc reduction).

// exponent at the order-2 cone point with CM discriminant d (one of -8, -20, -40):
d10cm_expo := func<d, F, p | KroneckerSymbol(d,p) eq 1 select F!(1/2) else F!(3/2)>;

// generic supersingular polynomial roots over F_{p^2}.  N = generic degree; known = set of >= 1
// known generic root (in F_p) to pin the accessory eigenvalue.  Returns ok, roots.
function d10cm_heun_generic(p, N, known)
  F := GF(p); F2 := GF(p^2);
  if N le 0 then return true, [F2|]; end if;
  R<s> := PolynomialRing(F);
  g := d10cm_expo(-8,F,p); d := d10cm_expo(-20,F,p); e := d10cm_expo(-40,F,p);
  ab := -F!N*(g+d+e-1+F!N);
  P := s*(s-1)*(s-2/27); Q := g*(s-1)*(s-2/27) + d*s*(s-2/27) + e*s*(s-1);
  // Heun operator A: f |-> P f'' + Q f' + ab*s*f, a square map on deg <= N (leading term cancels).
  M := ZeroMatrix(F, N+1, N+1);
  for j in [0..N] do
    img := P*Derivative(Derivative(s^j)) + Q*Derivative(s^j) + ab*s^(j+1);
    for k in [0..N] do M[k+1][j+1] := Coefficient(img, k); end for;
  end for;
  cands := [];
  for ev in Eigenvalues(M) do                                    // eigenvalue = accessory q
    for b in Basis(Kernel(Transpose(M - ev[1]*IdentityMatrix(F,N+1)))) do
      f := &+[b[k+1]*s^k : k in [0..N]];
      if Degree(f) eq N then Append(~cands, f/LeadingCoefficient(f)); end if;
    end for;
  end for;
  sel := [f : f in cands | &and[Evaluate(f,r) eq 0 : r in known]];
  if #sel ne 1 then return false, [F2|]; end if;                 // could not pin the eigenvalue
  return true, [F2| x[1] : x in Roots(ChangeRing(sel[1], F2))];
end function;

// full star supersingular coordinates over F_{p^2} (set of <coord,isInf>): generic points from
// the Heun polynomial plus the cone points 0, 1, 2/27, oo when supersingular.  Returns ok (false
// if the Heun eigenvalue cannot be pinned), checked against the star count on success.  The star
// count = genus(X_0(10,p)/full-AL) + 1 (the node count of the two-component special fiber), via the
// cheap genus formula rather than a Brandt-module computation.
function d10cm_star_coords(p)
  F2 := GF(p^2);
  star_n := GenusShimuraCurveQuotient(10, p, {Integers()|1,2,5,10}) + 1;
  ncone := #[d : d in [Integers()| -3,-8,-20,-40] | KroneckerSymbol(d,p) ne 1];
  known := d10cm_known_generic(p);
  if (star_n - ncone) gt 0 and #known eq 0 then return false, {}; end if;
  ok, gen := d10cm_heun_generic(p, star_n - ncone, [GF(p)!r : r in known]);
  if not ok then return false, {}; end if;
  star := { <r, false> : r in gen };
  if KroneckerSymbol(-8,p)  ne 1 then Include(~star, <F2!0, false>); end if;
  if KroneckerSymbol(-20,p) ne 1 then Include(~star, <F2!1, false>); end if;
  if KroneckerSymbol(-40,p) ne 1 then Include(~star, <F2!(2/27), false>); end if;
  if KroneckerSymbol(-3,p)  ne 1 then Include(~star, <F2!0, true>); end if;
  assert #star eq star_n;                                        // Heun + star-count self-check
  return true, star;
end function;

// lift the star supersingular coordinates through an intermediate cover y^2 = a s^2 + b s + c
// (s = X/Z) and project the resulting conic to P^1; returns the intermediate supersingular points
// as P^1 coordinates over F = F_{p^2}.  Shared by all discriminants (D=10, D=22, ...).
function cm_inter_conic_P1(p, a, b, c, starcoords)
  P2<X,Y,Z> := ProjectiveSpace(Rationals(),2);
  Cm := Curve(P2, Y^2 - a*X^2 - b*X*Z - c*Z^2);
  Fp := GF(p); F := GF(p^2);
  C := ChangeRing(Cm,Fp); Cc,CtoCc := Conic(C); _,P0 := HasRationalPoint(Cc); CP1,pi := Projection(Cc,P0);
  C2 := ChangeRing(Cm,F); C2c := ChangeRing(Cc,F); C2P1 := ChangeRing(CP1,F);
  am := AlgebraMap(CtoCc); m1 := map<C2->C2c | [am(Domain(am).i):i in [1..3]]>;
  am := AlgebraMap(pi);     m2 := map<C2c->C2P1 | [am(Domain(am).i):i in [1..2]]>;
  fmap := m1*m2;
  qss := [];
  for sc in starcoords do
    if sc[2] then                                          // s = oo : Z = 0, Y^2 = a
      val := F!a;
      cand := (val ne 0) select [[F!1, Sqrt(val), F!0],[F!1, -Sqrt(val), F!0]] else [[F!1, F!0, F!0]];
    else
      s0 := F!sc[1]; val := (F!a)*s0^2 + (F!b)*s0 + (F!c);
      cand := (val ne 0) select [[s0, Sqrt(val), F!1],[s0, -Sqrt(val), F!1]] else [[s0, F!0, F!1]];
    end if;
    for cp in cand do
      e := Eltseq(fmap(C2!cp));
      if not exists{T:T in qss | cm_eqP(e,T)} then Append(~qss, e); end if;
    end for;
  end for;
  return qss;
end function;

// D=10 intermediate X_0(10,1)/<w_q> via its cover equation f_q.
function d10cm_inter_P1(p, q, starcoords)
  cf := d10cm_fq[q];
  return cm_inter_conic_P1(p, cf[3], cf[2], cf[1], starcoords);
end function;

// lift the star supersingular coordinates to the BASE conic X_0(10,1) and project to P^1.
// The base is the Klein-four cover of the star (deck group <w_2,w_5>): a star coordinate s lifts
// to (z:w:t) on the conic z^2 + 25 w^2 + 2 t^2 = 0 via  w^2 = s/(s-1),  z = 2 y_2/(s-1)  with
// y_2^2 = f_2(s) = -1/4 (27s-2)(s-1)  (one verifies z^2+25w^2+2 = 0 identically); the four sign
// choices give the four base points over a generic s, collapsing to two at the order-2 cone
// points (s = 0, 1, 2/27) and to four order-3 points over s = oo.  Returns the base supersingular
// points as P^1 coordinates over F = F_{p^2}.
function d10cm_base_P1(p, starcoords)
  Fp := GF(p); F := GF(p^2);
  P2<Z,W,T> := ProjectiveSpace(Rationals(),2);
  Cm := Curve(P2, Z^2 + 25*W^2 + 2*T^2);
  C := ChangeRing(Cm,Fp); Cc,CtoCc := Conic(C); _,P0 := HasRationalPoint(Cc); CP1,pi := Projection(Cc,P0);
  C2 := ChangeRing(Cm,F); C2c := ChangeRing(Cc,F); C2P1 := ChangeRing(CP1,F);
  am := AlgebraMap(CtoCc); m1 := map<C2->C2c | [am(Domain(am).i):i in [1..3]]>;
  am := AlgebraMap(pi);     m2 := map<C2c->C2P1 | [am(Domain(am).i):i in [1..2]]>;
  fmap := m1*m2;
  f2 := func<s | -1/4*(27*s-2)*(s-1)>;
  cands := [];
  for sc in starcoords do
    if sc[2] then                                        // s = oo : w^2 -> 1, z = +-sqrt(-27)
      r := Sqrt(F!-27);
      for a in [r,-r] do for b in [F!1,F!-1] do Append(~cands, [a, b, F!1]); end for; end for;
    elif sc[1] eq 1 then                                 // s = 1 : w = oo, point at T = 0
      r := Sqrt(F!-1); Append(~cands, [5*r,F!1,F!0]); Append(~cands, [-5*r,F!1,F!0]);
    else
      s := sc[1]; w2 := s/(s-1); z0 := 2*Sqrt(f2(s))/(s-1);
      if w2 eq 0 then                                    // s = 0 : double w-root
        Append(~cands, [z0,F!0,F!1]); Append(~cands, [-z0,F!0,F!1]);
      else
        w0 := Sqrt(w2);
        if z0 eq 0 then                                  // s = 2/27 : double z-root
          Append(~cands, [F!0,w0,F!1]); Append(~cands, [F!0,-w0,F!1]);
        else
          for zz in [z0,-z0] do for ww in [w0,-w0] do Append(~cands, [zz,ww,F!1]); end for; end for;
        end if;
      end if;
    end if;
  end for;
  qss := [];
  for cp in cands do
    e := Eltseq(fmap(C2!cp));
    if not exists{TT:TT in qss | cm_eqP(e,TT)} then Append(~qss, e); end if;
  end for;
  return qss;
end function;

// star component X_0(10,1)* itself: the Hauptmodul s IS the P^1 coordinate on the star, so the
// supersingular points are the star coordinates directly (no lift).  Returns them as P^1 points
// over F = F_{p^2}.
function d10cm_star_P1(p, starcoords)
  F := GF(p^2);
  return [ sc[2] select [F!1, F!0] else [F!sc[1], F!1] : sc in starcoords ];
end function;

intrinsic SpecialFiberNotHyperellipticD10(N::RngIntElt, W::SetEnum) -> BoolElt, MonStgElt
{Special-fiber reduction-mod-p test for the discriminant-10 Shimura curve quotient X_0(10,N)/W.
Returns true with a witness if proven NOT geometrically hyperelliptic (a fortiori not
hyperelliptic over Q), otherwise false.  Implemented for N = p prime with the p-coprime component
group W'' the trivial group (the base X_0(10,1), the full degree-4 Klein-four cover), an intermediate
single-involution quotient by w_q (q = 2, 5 or 10), or the full Atkin-Lehner group (the star
X_0(10,1)*); other cases return false.  The
star supersingular points are computed in closed form from the (2,2,2,3) Heun Picard-Fuchs equation
(full coverage, no prime ceiling), with the accessory eigenvalue pinned by the precomputed rational
CM data and the count checked against the genus formula on every call; they are then lifted to the
relevant genus-0 component (base or intermediate) and the Mobius test applied.}
    for p in PrimeDivisors(N) do
        if 10 mod p eq 0 or N div p ne 1 then continue; end if;
        Wpp := {w div p^Valuation(w,p) : w in W};
        if Wpp notin {{Integers()|1},{Integers()|1,2},{Integers()|1,5},{Integers()|1,10},{Integers()|1,2,5,10}} then continue; end if;
        ok, sc := d10cm_star_coords(p);
        if not ok then continue; end if;                   // Heun eigenvalue could not be pinned
        case2 := exists{w : w in W | w mod p eq 0};
        F := GF(p^2);
        if Wpp eq {Integers()|1} then
            qss := d10cm_base_P1(p, sc);                   // base component X_0(10,1)
        elif Wpp eq {Integers()|1,2,5,10} then
            qss := d10cm_star_P1(p, sc);                   // star component X_0(10,1)*
        else
            qss := d10cm_inter_P1(p, Rep(Wpp diff {Integers()|1}), sc);   // intermediate X_0(10,1)/<w_q>
        end if;
        if cm_has_compat(qss, p, F, case2) eq "no" then
            return true, Sprintf("SpecialFiberD10 p=%o case=%o component=X_0(10,1)/%o", p, case2 select 2 else 1, Wpp);
        end if;
    end for;
    return false, _;
end intrinsic;

